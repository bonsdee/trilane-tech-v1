package com.trilanetech.api.file;

import com.trilanetech.api.common.AppProperties;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.regex.Pattern;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.core.io.FileSystemResource;
import org.springframework.core.io.Resource;
import org.springframework.stereotype.Component;

/** Keeps uploads in the folder named by UPLOAD_DIR. Use a persistent disk in production. */
@Component
public class LocalDiskFileStorage implements FileStorage {

    private static final Logger log = LoggerFactory.getLogger(LocalDiskFileStorage.class);
    /** Keys are generated by the server; anything else is refused, so no path can escape the folder. */
    private static final Pattern SAFE_KEY = Pattern.compile("^[a-f0-9-]{36}\\.(jpg|png|webp)$");

    private final Path root;

    public LocalDiskFileStorage(AppProperties props) throws IOException {
        this.root = Path.of(props.uploads().dir()).toAbsolutePath().normalize();
        Files.createDirectories(root);
        log.info("Storing uploaded images in {}", root);
    }

    @Override
    public void store(String key, byte[] content) throws IOException {
        Files.write(resolve(key), content, StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE);
    }

    @Override
    public Resource load(String key) {
        Path path = resolve(key);
        return Files.isRegularFile(path) ? new FileSystemResource(path) : null;
    }

    @Override
    public void delete(String key) throws IOException {
        Files.deleteIfExists(resolve(key));
    }

    private Path resolve(String key) {
        if (key == null || !SAFE_KEY.matcher(key).matches()) {
            throw new IllegalArgumentException("Invalid storage key");
        }
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root)) {
            throw new IllegalArgumentException("Invalid storage key");
        }
        return path;
    }
}
